// Writes web/src/lib/related.golden.json: the fixture for the ranker's golden test.
//
//   node docs/recommendations-research/golden-fixture.mjs
//
// Hand-run, once, and never by the build or the tests. Reads files only, spends no quota and
// queries no dataset: the corpus, the v5 tag set and the M3.5 report, all from the lab. The test
// reads the fixture alone, so it runs anywhere and never changes under a re-fetch.
//
// ── WHAT THE FIXTURE PROVES ──────────────────────────────────────────────────────────────────
//
// It is stream 2's guard against the port drifting from what Andy judged
// (stream-2-ranker.md → piece 3). It carries two things:
//
//   - the 73 judged documents as the ranker saw them in M3.5: ids, slugs, types, genres, dates,
//     and v5's tags shaped as RELATED_POOL_QUERY projects them, each with its score. No text.
//   - M3.5's v5 column, read back from m3.5.md, the report Andy marked. That column was written
//     by the research's copy of the ranker, so the golden test holds the shipped module to it.
//
// The test also ranks the same pool with the scores removed, the lists stream 2 ships, and
// records those as a node:test snapshot beside it. That half is not derived here: a snapshot is
// the test's own record, and this script only extracts facts that exist independently of it.
//
// ── THE TAG SHAPES ARE REBUILT EXACTLY AS M3.5 REBUILT THEM ──────────────────────────────────
//
// A tag set holds bare concept ids; taxonomy-columns.mjs's topicShaper and withTagSet give each
// its first parent and `parentIsTop` from corpus.json's Topic scheme, and checkShape proves the
// rebuild against what the query projected. Reusing them, rather than reimplementing them, is
// what makes the fixture the pool M3.5 ranked.
//
// ── SLUGS, NOT IDS, IN THE EXPECTED LISTS ────────────────────────────────────────────────────
//
// A failing golden test prints a diff. Slugs make it readable, and the script checks they are
// unique before using them as keys.
import {readFileSync, writeFileSync} from 'node:fs'
import {parseReport} from './m3-parse.mjs'
import {checkShape, loadTagSet, topicShaper, withTagSet} from './taxonomy-columns.mjs'

const REPORT = 'm3.5.md'
const TAG_SET = 'v5'
const OUT = new URL('../../web/src/lib/related.golden.json', import.meta.url)

const corpus = JSON.parse(readFileSync(new URL('./corpus.json', import.meta.url)))
const tagSet = loadTagSet(TAG_SET)
const report = parseReport(readFileSync(new URL(`./${REPORT}`, import.meta.url), 'utf8'))

/* ── The sources must agree with each other before anything is written ── */

for (const [name, dataset] of [
  ['corpus.json', corpus.dataset],
  [`tagsets/${TAG_SET}.json`, tagSet.dataset],
]) {
  if (dataset !== 'recommendations-lab') throw new Error(`${name} is from ${dataset}, not the lab`)
}
const ids = (xs, key = '_id') =>
  xs
    .map((x) => x[key])
    .sort()
    .join()
if (ids(tagSet.documents) !== ids(corpus.pool)) {
  throw new Error(`tagsets/${TAG_SET}.json and corpus.json hold different documents`)
}
if (ids(report.pages, 'id') !== ids(corpus.pool)) {
  throw new Error(`${REPORT} and corpus.json hold different documents`)
}
if (new Set(corpus.pool.map((d) => d.slug)).size !== corpus.pool.length) {
  throw new Error('two documents share a slug, so slugs cannot key the expected lists')
}

/* ── The pool, as M3.5 ranked it ── */

const shape = topicShaper(corpus.topicScheme)
checkShape(corpus.pool, shape)
const pool = withTagSet(corpus.pool, tagSet, shape).map((d) => ({
  _id: d._id,
  slug: d.slug,
  _type: d._type,
  genreId: d.genreId,
  pubDate: d.pubDate,
  topics: d.topics.map(({_id, parent, parentIsTop, score}) => ({_id, parent, parentIsTop, score})),
}))

/* ── M3.5's v5 column, by slug ── */

const slugOfTitle = new Map(corpus.pool.map((d) => [d.title.trim(), d.slug]))
const slugOfId = new Map(corpus.pool.map((d) => [d._id, d.slug]))
const v5 = {}
for (const page of report.pages) {
  const column = page.columns.find((c) => c.name === TAG_SET)
  if (!column) throw new Error(`${REPORT} has no ${TAG_SET} column for ${slugOfId.get(page.id)}`)
  const items = column.cards.filter(Boolean).map((title) => {
    const slug = slugOfTitle.get(title)
    if (!slug) throw new Error(`no document titled "${title}"`)
    return slug
  })
  v5[slugOfId.get(page.id)] = {items, isFallback: column.recent}
}

const fixture = {
  about:
    "The related-content ranker's golden fixture. Generated by " +
    'docs/recommendations-research/golden-fixture.mjs; do not edit by hand.',
  source: {
    corpus: {file: 'docs/recommendations-research/corpus.json', fetchedAt: corpus.fetchedAt},
    tagSet: {
      file: `docs/recommendations-research/tagsets/${TAG_SET}.json`,
      createdAt: tagSet.createdAt,
    },
    report: `docs/recommendations-research/${REPORT}`,
  },
  /* The rule M3.5 ranked v5 under, as the tag set records it. */
  rule: {...tagSet.crossRule, tieBreak: tagSet.tieBreak},
  genres: {
    tops: corpus.genres.tops.map(({_id, prefLabel}) => ({_id, prefLabel})),
    concepts: corpus.genres.concepts.map(({_id, prefLabel, broader}) => ({
      _id,
      prefLabel,
      broader,
    })),
  },
  /* Newest first, as RELATED_POOL_QUERY returns it: the ranker's only notion of date. */
  pool,
  v5,
}

writeFileSync(OUT, JSON.stringify(fixture, null, 2) + '\n')
console.log(`wrote ${OUT.pathname}: ${pool.length} documents, ${Object.keys(v5).length} v5 lists`)
